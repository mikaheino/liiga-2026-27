-- Uutistaulujen julkaisija (23.11.2026, katselmointi m6): recompute.yml / scripts/news/publish_news.py.
-- Vain SELECT, INSERT ja DELETE kahteen tauluun; ei DDL:ää eikä muuta dataa. Sama CI-käyttäjä LIIGA_CI
-- (publish_news.py avaa yhteyden roolilla LIIGA_NEWS_PUBLISHER). Taulujen omistaja pysyy LIIGA_ADMIN.
-- Aja ACCOUNTADMINina: snow sql -c futurice --role ACCOUNTADMIN -f snowflake/_account/roles/LIIGA_NEWS_PUBLISHER.sql
USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS LIIGA_NEWS_PUBLISHER COMMENT = 'Liiga: uutistaulujen julkaisu GitHubista (recompute.yml)';
GRANT ROLE LIIGA_NEWS_PUBLISHER TO USER LIIGA_CI;
GRANT ROLE LIIGA_NEWS_PUBLISHER TO ROLE LIIGA_ADMIN;
GRANT USAGE ON WAREHOUSE LIIGA_WH TO ROLE LIIGA_NEWS_PUBLISHER;
GRANT USAGE ON DATABASE LIIGA TO ROLE LIIGA_NEWS_PUBLISHER;
GRANT USAGE ON SCHEMA LIIGA.MODEL TO ROLE LIIGA_NEWS_PUBLISHER;
GRANT SELECT, INSERT, DELETE ON TABLE LIIGA.MODEL.NEWS_SIGNALS TO ROLE LIIGA_NEWS_PUBLISHER;
GRANT SELECT, INSERT, DELETE ON TABLE LIIGA.MODEL.NEWS_ABSENCE_LOG TO ROLE LIIGA_NEWS_PUBLISHER;
-- Julkaisurooli ei enää kirjoita uutistauluihin (22.11. väliaikainen oikeus).
REVOKE INSERT, DELETE ON TABLE LIIGA.MODEL.NEWS_SIGNALS FROM ROLE LIIGA_DEPLOYER;
REVOKE INSERT, DELETE ON TABLE LIIGA.MODEL.NEWS_ABSENCE_LOG FROM ROLE LIIGA_DEPLOYER;
-- Avainsarakkeet eivät saa olla NULL (katselmointi m1); publish_news.py suodattaa NULL-avaimet pois ennen kirjoitusta.
ALTER TABLE LIIGA.MODEL.NEWS_SIGNALS ALTER COLUMN TEAM SET NOT NULL, COLUMN KIND SET NOT NULL, COLUMN PLAYER SET NOT NULL;
ALTER TABLE LIIGA.MODEL.NEWS_ABSENCE_LOG ALTER COLUMN URL_HASH SET NOT NULL, COLUMN KIND SET NOT NULL,
  COLUMN PLAYER SET NOT NULL, COLUMN TEAM SET NOT NULL;
