-- Aamusynkan rooli: kirjoittaa vain paikallisen ajon julkaisemat kuratoidut
-- taulut (snowflake_sync.CURATED_TABLES). CREATE OR REPLACE vaatii omistajuuden,
-- siksi taulujen omistajuus siirretään tälle roolille. EI raw_gamesia: notebook
-- (ACCOUNTADMIN) luo sen uudelleen.
--
-- Aja ACCOUNTADMINina: snow sql -c CONTAINER_SERVICES --role ACCOUNTADMIN -f snowflake/_account/roles/LIIGA_LOADER.sql
-- Idempotentti. Koko tilin järjestys: snowflake/_account/README.md.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS LIIGA_LOADER
  COMMENT = 'Liiga: paikallisen ajon julkaisemat taulut Snowflakeen (aamusynkka).';

GRANT ROLE LIIGA_LOADER TO ROLE SYSADMIN;

GRANT ROLE LIIGA_LOADER TO USER MHEINO;

GRANT USAGE ON WAREHOUSE LIIGA_WH TO ROLE LIIGA_LOADER;

GRANT USAGE ON DATABASE LIIGA TO ROLE LIIGA_LOADER;

GRANT USAGE ON SCHEMA LIIGA.RAW TO ROLE LIIGA_LOADER;

GRANT USAGE ON SCHEMA LIIGA.MODEL TO ROLE LIIGA_LOADER;

GRANT USAGE ON SCHEMA LIIGA.CODE TO ROLE LIIGA_LOADER;

GRANT CREATE TABLE ON SCHEMA LIIGA.RAW TO ROLE LIIGA_LOADER;

GRANT CREATE TABLE ON SCHEMA LIIGA.MODEL TO ROLE LIIGA_LOADER;

-- Lataus: Parquet-tiedostot stagelle, INFER_SCHEMA + COPY.
GRANT READ, WRITE ON STAGE LIIGA.CODE.LOAD_STAGE TO ROLE LIIGA_LOADER;

GRANT USAGE ON FILE FORMAT LIIGA.CODE.PARQUET_FMT TO ROLE LIIGA_LOADER;

-- Git-repon päivitys (sync_to_snowflake.py --code).
GRANT READ, WRITE ON GIT REPOSITORY LIIGA.CODE.LIIGA_REPO TO ROLE LIIGA_LOADER;

-- Synkattavien taulujen omistajuus.
GRANT OWNERSHIP ON TABLE LIIGA.RAW.LEAGUE_FACTORS TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;

GRANT OWNERSHIP ON TABLE LIIGA.RAW.RAW_EXTERNAL_PLAYER_SEASONS TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;

GRANT OWNERSHIP ON TABLE LIIGA.RAW.RAW_GOALIE_SEASONS TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;

GRANT OWNERSHIP ON TABLE LIIGA.RAW.ROSTER_2026_27 TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;

GRANT OWNERSHIP ON TABLE LIIGA.RAW.PLAYER_BIO TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;

GRANT OWNERSHIP ON TABLE LIIGA.RAW.PRESEASON_PLAYER_RATES TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;

GRANT OWNERSHIP ON TABLE LIIGA.MODEL.PLAYER_RATES TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;

GRANT OWNERSHIP ON TABLE LIIGA.MODEL.PLAYER_RATES_LIIGA TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;

GRANT OWNERSHIP ON TABLE LIIGA.MODEL.PLAYER_RATES_UNIFIED TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;

-- Loukkaantumissimulaattorin maalivahtipainot (goalies.py, 16.10.); synkka kaatui ilman tätä 16.-23.10.
GRANT OWNERSHIP ON TABLE LIIGA.MODEL.TEAM_GOALIE_WEIGHTS TO ROLE LIIGA_LOADER COPY CURRENT GRANTS;
