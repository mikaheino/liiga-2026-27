-- Julkaisurooli ja GitHub Actionsin palvelukäyttäjä (2026-10-16).
--
--   LIIGA_DEPLOYER  julkaisee näkymät, semanttiset mallit, agentin ja skillit
--                   sekä ajaa evaluoinnit. Käytetään SEKÄ paikallisesti että
--                   CI:ssä (scripts/snow_conn.py oletus), jotta objektien
--                   omistajuus ei heilu: ACCOUNTADMINin CREATE OR REPLACE
--                   veisi omistajuuden takaisin ja seuraava CI-ajo kaatuisi.
--   LIIGA_CI        TYPE = SERVICE -käyttäjä, vain avainparitunnistus. Julkinen
--                   avain asetetaan erikseen (ALTER USER ... SET RSA_PUBLIC_KEY),
--                   yksityinen avain on vain GitHubin salaisuutena.
--
-- Ei saa: dataa kirjoittavia oikeuksia RAW/MODEL-tauluihin (data tulee
-- notebookista ja paikallisesta synkasta, ei CI:stä), käyttäjien tai roolien
-- hallintaa, eikä CoWork-objektin muokkausta.
--
-- Aja: snow sql -c CONTAINER_SERVICES --role ACCOUNTADMIN -f snowflake/ci_user.sql

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS LIIGA_DEPLOYER
  COMMENT = 'Liiga Ennustaja: näkymien, semanttisten mallien, agentin ja evaluointien julkaisu (paikallinen + CI).';
GRANT ROLE LIIGA_DEPLOYER TO ROLE SYSADMIN;
GRANT ROLE LIIGA_DEPLOYER TO USER MHEINO;
-- Agenttien hallinta (MODIFY, COMMIT, aliakset) omistajaroolin kautta.
GRANT ROLE LIIGA_AGENT_OWNER TO ROLE LIIGA_DEPLOYER;

GRANT USAGE ON WAREHOUSE LIIGA_WH TO ROLE LIIGA_DEPLOYER;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE LIIGA_DEPLOYER;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE LIIGA_DEPLOYER;      -- evaluointiajo luo taustatehtävän

-- Luku: näkymät lukevat MODEL- ja RAW-tauluja omistajansa oikeuksin.
GRANT USAGE ON DATABASE LIIGA TO ROLE LIIGA_DEPLOYER;
GRANT USAGE ON SCHEMA LIIGA.MODEL TO ROLE LIIGA_DEPLOYER;
GRANT USAGE ON SCHEMA LIIGA.RAW TO ROLE LIIGA_DEPLOYER;
GRANT SELECT ON ALL TABLES IN SCHEMA LIIGA.MODEL TO ROLE LIIGA_DEPLOYER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LIIGA.MODEL TO ROLE LIIGA_DEPLOYER;
GRANT SELECT ON ALL TABLES IN SCHEMA LIIGA.RAW TO ROLE LIIGA_DEPLOYER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LIIGA.RAW TO ROLE LIIGA_DEPLOYER;

-- Luonti: näkymät ja semanttiset mallit.
GRANT CREATE VIEW ON SCHEMA LIIGA.MODEL TO ROLE LIIGA_DEPLOYER;
GRANT CREATE SEMANTIC VIEW ON SCHEMA LIIGA.MODEL TO ROLE LIIGA_DEPLOYER;

-- Skillit: versiokohtaiset kansiot stagelle.
GRANT USAGE ON SCHEMA LIIGA.CODE TO ROLE LIIGA_DEPLOYER;
GRANT READ, WRITE ON STAGE LIIGA.CODE.AGENT_SKILLS TO ROLE LIIGA_DEPLOYER;

-- Evaluoinnit.
CREATE SCHEMA IF NOT EXISTS LIIGA.EVALS;
GRANT USAGE ON SCHEMA LIIGA.EVALS TO ROLE LIIGA_DEPLOYER;
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE TASK, CREATE DATASET
  ON SCHEMA LIIGA.EVALS TO ROLE LIIGA_DEPLOYER;

-- Nykyisten julkaisuobjektien omistajuus julkaisuroolille. Tuotannon vanhat
-- mallit LIIGA_ENNUSTAJA_SV ja LIIGA_KAUSI_SV jäävät ACCOUNTADMINille
-- tarkoituksella: VERSION$2 viittaa niihin, ja ne ovat jäädytettyjä.
GRANT OWNERSHIP ON ALL VIEWS IN SCHEMA LIIGA.MODEL TO ROLE LIIGA_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SEMANTIC VIEW LIIGA.MODEL.LIIGA_ENNUSTAJA_SV_DEV TO ROLE LIIGA_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SEMANTIC VIEW LIIGA.MODEL.LIIGA_KAUSI_SV_DEV TO ROLE LIIGA_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA LIIGA.EVALS TO ROLE LIIGA_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL STAGES IN SCHEMA LIIGA.EVALS TO ROLE LIIGA_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL FILE FORMATS IN SCHEMA LIIGA.EVALS TO ROLE LIIGA_DEPLOYER COPY CURRENT GRANTS;

-- GitHub Actionsin palvelukäyttäjä. Ei salasanaa: TYPE = SERVICE ei voi
-- kirjautua salasanalla eikä selaimella.
CREATE USER IF NOT EXISTS LIIGA_CI
  TYPE = SERVICE
  DEFAULT_ROLE = LIIGA_DEPLOYER
  DEFAULT_WAREHOUSE = LIIGA_WH
  COMMENT = 'GitHub Actions: mikaheino/liiga-2026-27 julkaisu. Avainparitunnistus.';
GRANT ROLE LIIGA_DEPLOYER TO USER LIIGA_CI;
